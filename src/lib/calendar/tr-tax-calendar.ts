// Faz 46 (C3) — Deterministic Turkish Statutory Tax & SGK Obligation Calendar Engine.
//
// Legal basis:
// - KDV-2 (Sorumlu Sıfatıyla Tevkifat KDV): 25th of following month (beyan ve ödeme)
// - MPHB (Muhtasar ve Prim Hizmet Beyannamesi — Stopaj/Damga): 26th of following month
// - KDV-1 (Katma Değer Vergisi): 28th of following month
// - SGK 4/a İşveren ve İşçi Sigorta Primleri: last calendar day of following month
// - Kurumlar Geçici Vergi (4 Dönem — 7566 Sayılı Kanun uyumlu):
//     Q1 -> 17 Mayıs, Q2 -> 17 Ağustos, Q3 -> 17 Kasım, Q4 -> takip eden yıl 17 Şubat
// - Kurumlar Vergisi Yıllık Beyan ve Ödeme: takip eden yıl 30 Nisan
// - Motorlu Taşıtlar Vergisi (MTV 1. ve 2. Taksit): 31 Ocak ve 31 Temmuz
//
// NOTE: Form Ba / Form Bs were abolished in September 2024 (VUK Genel Tebliği Sıra No: 565)
// and are NEVER generated by this engine.
// Every statutory deadline is rolled forward to the first Turkish business day via VUK Md. 18.

import { nextTurkishBusinessDay } from "./tr-holidays";

export type TrStatutoryTaxCode =
  | "KDV_2"
  | "MPHB"
  | "KDV_1"
  | "SGK_4A"
  | "KURUMLAR_GECICI_VERGI"
  | "KURUMLAR_VERGISI_YILLIK"
  | "MTV_TAKSIT_1"
  | "MTV_TAKSIT_2";

export interface TrStatutoryObligation {
  id: string;
  code: TrStatutoryTaxCode;
  label: string;
  taxPeriod: string;
  statutoryNominalDate: string;
  effectiveDueDate: string;
  shiftedFrom: string | null;
  shiftReason: string | null;
  currency: "TRY";
  hardDeadline: true;
  authority: "GIB" | "SGK";
}

function pad2(n: number): string {
  return String(n).padStart(2, "0");
}

function daysInMonthUtc(year: number, month1to12: number): number {
  return new Date(Date.UTC(year, month1to12, 0)).getUTCDate();
}

function buildEntry(input: {
  code: TrStatutoryTaxCode;
  label: string;
  taxPeriod: string;
  nominalDate: string;
  authority: "GIB" | "SGK";
}): TrStatutoryObligation {
  const shifted = nextTurkishBusinessDay(input.nominalDate);
  return {
    id: `tr-tax:${input.code}:${input.taxPeriod}`,
    code: input.code,
    label: input.label,
    taxPeriod: input.taxPeriod,
    statutoryNominalDate: input.nominalDate,
    effectiveDueDate: shifted.effectiveDate,
    shiftedFrom: shifted.shiftedFrom,
    shiftReason: shifted.reason,
    currency: "TRY",
    hardDeadline: true,
    authority: input.authority,
  };
}

/**
 * Generate all statutory tax and SGK deadlines whose nominal or effective due date falls inside
 * `[fromISO, toISO]` (inclusive). Pure & deterministic.
 */
export function generateTrStatutoryObligations(
  fromISO: string,
  toISO: string,
): TrStatutoryObligation[] {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(fromISO) || !/^\d{4}-\d{2}-\d{2}$/.test(toISO)) {
    throw new Error(`Geçersiz tarih aralığı: ${fromISO} .. ${toISO}`);
  }
  if (toISO < fromISO) return [];

  const startYear = Number(fromISO.slice(0, 4)) - 1;
  const endYear = Number(toISO.slice(0, 4)) + 1;
  const all: TrStatutoryObligation[] = [];

  for (let year = startYear; year <= endYear; year += 1) {
    // 1. Monthly obligations for tax period YYYY-MM (due in the following month)
    for (let month = 1; month <= 12; month += 1) {
      const periodKey = `${year}-${pad2(month)}`;
      const dueYear = month === 12 ? year + 1 : year;
      const dueMonth = month === 12 ? 1 : month + 1;
      const dueLastDay = daysInMonthUtc(dueYear, dueMonth);

      all.push(
        buildEntry({
          code: "KDV_2",
          label: `KDV-2 (Tevkifat KDV) Beyan ve Ödeme (${periodKey})`,
          taxPeriod: periodKey,
          nominalDate: `${dueYear}-${pad2(dueMonth)}-25`,
          authority: "GIB",
        }),
        buildEntry({
          code: "MPHB",
          label: `Muhtasar ve Prim Hizmet Beyannamesi — MPHB (${periodKey})`,
          taxPeriod: periodKey,
          nominalDate: `${dueYear}-${pad2(dueMonth)}-26`,
          authority: "GIB",
        }),
        buildEntry({
          code: "KDV_1",
          label: `KDV-1 Beyan ve Ödeme (${periodKey})`,
          taxPeriod: periodKey,
          nominalDate: `${dueYear}-${pad2(dueMonth)}-28`,
          authority: "GIB",
        }),
        buildEntry({
          code: "SGK_4A",
          label: `SGK 4/a Sigorta Primleri Ödemesi (${periodKey})`,
          taxPeriod: periodKey,
          nominalDate: `${dueYear}-${pad2(dueMonth)}-${pad2(dueLastDay)}`,
          authority: "SGK",
        }),
      );
    }

    // 2. Kurumlar Geçici Vergi — 4 periods (Law No. 7566 restored Q4 Geçici Vergi!)
    all.push(
      buildEntry({
        code: "KURUMLAR_GECICI_VERGI",
        label: `Kurumlar Geçici Vergi 1. Dönem (${year}-Q1)`,
        taxPeriod: `${year}-Q1`,
        nominalDate: `${year}-05-17`,
        authority: "GIB",
      }),
      buildEntry({
        code: "KURUMLAR_GECICI_VERGI",
        label: `Kurumlar Geçici Vergi 2. Dönem (${year}-Q2)`,
        taxPeriod: `${year}-Q2`,
        nominalDate: `${year}-08-17`,
        authority: "GIB",
      }),
      buildEntry({
        code: "KURUMLAR_GECICI_VERGI",
        label: `Kurumlar Geçici Vergi 3. Dönem (${year}-Q3)`,
        taxPeriod: `${year}-Q3`,
        nominalDate: `${year}-11-17`,
        authority: "GIB",
      }),
      buildEntry({
        code: "KURUMLAR_GECICI_VERGI",
        label: `Kurumlar Geçici Vergi 4. Dönem (${year}-Q4 — 7566 Sayılı Kanun)`,
        taxPeriod: `${year}-Q4`,
        nominalDate: `${year + 1}-02-17`,
        authority: "GIB",
      }),
    );

    // 3. Annual Kurumlar Vergisi (for accounting year `year`, due 30 April of `year + 1`)
    all.push(
      buildEntry({
        code: "KURUMLAR_VERGISI_YILLIK",
        label: `Kurumlar Vergisi Yıllık Beyan ve Ödeme (${year})`,
        taxPeriod: `${year}`,
        nominalDate: `${year + 1}-04-30`,
        authority: "GIB",
      }),
    );

    // 4. MTV 1st & 2nd Installments (31 January & 31 July of `year`)
    all.push(
      buildEntry({
        code: "MTV_TAKSIT_1",
        label: `Motorlu Taşıtlar Vergisi (MTV) 1. Taksit (${year})`,
        taxPeriod: `${year}-H1`,
        nominalDate: `${year}-01-31`,
        authority: "GIB",
      }),
      buildEntry({
        code: "MTV_TAKSIT_2",
        label: `Motorlu Taşıtlar Vergisi (MTV) 2. Taksit (${year})`,
        taxPeriod: `${year}-H2`,
        nominalDate: `${year}-07-31`,
        authority: "GIB",
      }),
    );
  }

  return all
    .filter((item) => item.effectiveDueDate >= fromISO && item.effectiveDueDate <= toISO)
    .sort(
      (a, b) =>
        a.effectiveDueDate.localeCompare(b.effectiveDueDate)
        || a.statutoryNominalDate.localeCompare(b.statutoryNominalDate)
        || a.id.localeCompare(b.id),
    );
}

export function generateTrStatutoryObligationsForYear(year: number): TrStatutoryObligation[] {
  return generateTrStatutoryObligations(`${year}-01-01`, `${year}-12-31`);
}

