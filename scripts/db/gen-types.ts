// Generates src/types/database.ts from the live verified local schema
// (Phase 1 deliverable "generated database types"; supabase CLI unreachable here,
// so generation reads information_schema of the migration-verified database).
import { Client } from "pg";
import { writeFileSync } from "node:fs";

const TS: Record<string, string> = {
  uuid: "string", text: "string", date: "string", timestamptz: "string",
  "timestamp with time zone": "string", int4: "number", integer: "number",
  numeric: "number", bool: "boolean", boolean: "boolean", jsonb: "Json",
  ARRAY: "string[]", _text: "string[]",
};

function pascal(s: string) {
  return s.split("_").map((w) => w[0].toUpperCase() + w.slice(1)).join("");
}

async function main() {
  const c = new Client({
    host: "127.0.0.1", user: "postgres", password: "postgres", database: "mas_radar_verify",
  });
  await c.connect();
  const tables = await c.query(
    `select tablename from pg_tables where schemaname='public' order by tablename`,
  );
  const out: string[] = [
    "// AUTO-GENERATED by scripts/db/gen-types.ts from the migration-verified schema.",
    "// Do not edit by hand. Regenerate: pnpm db:types",
    "",
    "export type Json = string | number | boolean | null | { [key: string]: Json } | Json[];",
    "",
  ];
  const names: string[] = [];
  for (const { tablename } of tables.rows) {
    const cols = await c.query(
      `select column_name, udt_name, data_type, is_nullable, column_default, is_generated
       from information_schema.columns
       where table_schema='public' and table_name=$1 order by ordinal_position`,
      [tablename],
    );
    const row: string[] = [];
    const insert: string[] = [];
    for (const col of cols.rows) {
      const base = TS[col.udt_name] ?? TS[col.data_type] ?? "unknown";
      const nullable = col.is_nullable === "YES";
      row.push(`  ${col.column_name}: ${base}${nullable ? " | null" : ""};`);
      if (col.is_generated === "ALWAYS") continue;
      const optional = nullable || col.column_default !== null;
      insert.push(`  ${col.column_name}${optional ? "?" : ""}: ${base}${nullable ? " | null" : ""};`);
    }
    const P = pascal(tablename);
    names.push(tablename);
    out.push(`export interface ${P}Row {`, ...row, "}", "");
    out.push(`export interface ${P}Insert {`, ...insert, "}", "");
  }
  out.push("export interface Database {", "  public: {", "    Tables: {");
  for (const t of names) out.push(`      ${t}: { Row: ${pascal(t)}Row; Insert: ${pascal(t)}Insert };`);
  out.push("    };", "  };", "}", "");
  writeFileSync("src/types/database.ts", out.join("\n"));
  console.log(`generated src/types/database.ts — ${names.length} tables`);
  await c.end();
}
main().catch((e) => { console.error(e); process.exit(1); });
